import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { MemoryFs, ProjectStore } from "@mse/core";
import { createServer } from "./server";

type Schema = {
  $ref?: string;
  type?: string;
  description?: string;
  enum?: unknown[];
  const?: unknown;
  items?: Schema;
  anyOf?: Schema[];
  oneOf?: Schema[];
  properties?: Record<string, Schema>;
  required?: string[];
  minimum?: number;
  maximum?: number;
  additionalProperties?: Schema | boolean;
};

/** zod reuses one definition by pointing at it ("$ref": "#/properties/..."); follow the pointer inside the same tool schema. */
let root: Schema = {};
function deref(s: Schema): Schema {
  if (!s.$ref?.startsWith("#/")) return s;
  let cur: unknown = root;
  for (const seg of s.$ref.slice(2).split("/")) cur = (cur as Record<string, unknown> | undefined)?.[seg.replace(/~1/g, "/").replace(/~0/g, "~")];
  return cur ? { ...(cur as Schema), description: s.description ?? (cur as Schema).description } : s;
}

const variants = (s: Schema) => s.oneOf ?? s.anyOf;
const isOpUnion = (s?: Schema) => !!s && !!variants(s)?.every((v) => v.properties?.op?.const !== undefined);

/** A short, human type for one parameter. */
function typeOf(input: Schema): string {
  const s = deref(input);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" \\| ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  const alt = variants(s);
  if (alt) return isOpUnion({ anyOf: alt }) ? "op" : alt.map(typeOf).join(" \\| ");
  if (s.type === "array") return `${typeOf(s.items ?? {})}[]`;
  if (s.type === "object" && s.additionalProperties && typeof s.additionalProperties === "object") return `map of ${typeOf(s.additionalProperties)}`;
  const range = s.minimum !== undefined || s.maximum !== undefined ? ` (${s.minimum ?? ""}..${s.maximum ?? ""})` : "";
  return `${s.type ?? "any"}${range}`;
}

const esc = (t: string) => t.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();

function paramTable(props: Record<string, Schema>, required: string[] = []): string[] {
  if (!Object.keys(props).length) return [];
  const rows = ["| Parameter | Type | Required | Notes |", "|---|---|---|---|"];
  for (const [name, raw] of Object.entries(props)) {
    const s = deref(raw);
    rows.push(`| \`${name}\` | ${typeOf(s)} | ${required.includes(name) ? "yes" : "no"} | ${esc(s.description ?? "")} |`);
  }
  return rows;
}

const GROUPS: [string, (n: string) => boolean][] = [
  ["Project", (n) => n === "project_info" || n === "project_validate"],
  ["Sprites and drawing", (n) => n.startsWith("sprite_") || n.startsWith("sheet_")],
  ["Tilesets and animations", (n) => n.startsWith("tileset_") || n.startsWith("tile_") || n.startsWith("animation_")],
  ["Maps", (n) => n.startsWith("map_") || n.startsWith("layer_") || n.startsWith("entity_")],
  ["Sprite requests", (n) => n.startsWith("request_")],
  ["Export", (n) => n.startsWith("export_")],
];

/** Markdown reference of every tool and prompt, generated from the live server so it cannot drift. */
export async function renderToolDocs(): Promise<string> {
  const server = createServer(new ProjectStore(new MemoryFs(), "/p"), new MemoryFs());
  const client = new Client({ name: "docs", version: "0" });
  const [a, b] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(a), client.connect(b)]);
  const tools = (await client.listTools()).tools;
  const prompts = (await client.listPrompts()).prompts;
  await client.close();

  const out: string[] = [
    "# MCP tool reference",
    "",
    "<!-- Generated by `pnpm docs:tools` from the running server. Do not edit by hand: a test fails when this file is out of date. -->",
    "",
    `The server offers **${tools.length} tools** and **${prompts.length} prompts**. Coordinates start at (0,0) in the top-left corner.`,
    "Map cells are `x` (column) and `y` (row); entity positions are in map **pixels**. Tile numbers in maps are 1-based (`0` means empty).",
    "Tools never throw: a problem comes back as an error result with a message you can act on.",
    "",
    "See the [MCP guide](mcp-guide.md) for how to connect and for worked examples.",
    "",
  ];

  const used = new Set<string>();
  for (const [title, match] of GROUPS) {
    const group = tools.filter((t) => match(t.name));
    if (!group.length) continue;
    out.push(`## ${title}`, "");
    for (const t of group) {
      used.add(t.name);
      const schema = t.inputSchema as Schema;
      root = schema;
      out.push(`### \`${t.name}\``, "", t.description ?? "", "");
      const table = paramTable(schema.properties ?? {}, schema.required);
      out.push(...(table.length ? table : ["_No parameters._"]), "");
      // ops of sprite_draw: one table per variant
      for (const [pname, p] of Object.entries(schema.properties ?? {})) {
        if (p.type === "array" && isOpUnion(p.items)) {
          out.push(`**\`${pname}\` items** (each has an \`op\`):`, "");
          for (const v of variants(p.items!)!) {
            const { op, ...rest } = v.properties!;
            const rows = paramTable(rest, (v.required ?? []).filter((r) => r !== "op"));
            out.push(`- \`${JSON.stringify(op!.const)}\`${rows.length ? "" : " (no fields)"}`);
            if (rows.length) out.push("", ...rows.map((r) => `  ${r}`), "");
          }
          out.push("");
        }
      }
    }
  }
  const rest = tools.filter((t) => !used.has(t.name));
  if (rest.length) {
    out.push("## Other", "");
    for (const t of rest) out.push(`### \`${t.name}\``, "", t.description ?? "", "");
  }

  out.push("## Prompts", "", "Prompts are ready-made briefs your client can offer as commands (in Claude Code they appear as `/mcp__<server>__<prompt>`).", "");
  for (const p of prompts) {
    out.push(`### \`${p.name}\``, "", p.description ?? "", "");
    if (p.arguments?.length) {
      out.push("| Argument | Required | Notes |", "|---|---|---|");
      for (const arg of p.arguments) out.push(`| \`${arg.name}\` | ${arg.required ? "yes" : "no"} | ${esc(arg.description ?? "")} |`);
      out.push("");
    }
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}
